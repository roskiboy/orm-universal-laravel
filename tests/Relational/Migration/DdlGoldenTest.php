<?php

declare(strict_types=1);

namespace OrmUniversal\Relational\Tests\Migration;

use OrmUniversal\Contracts\Enums\TypeKind;
use OrmUniversal\Contracts\ValueObjects\ColumnDefinition;
use OrmUniversal\Contracts\ValueObjects\ForeignKeyDefinition;
use OrmUniversal\Contracts\ValueObjects\IndexDefinition;
use OrmUniversal\Contracts\ValueObjects\TableDefinition;
use OrmUniversal\Relational\Dialect\MariaDbDialect;
use OrmUniversal\Relational\Dialect\MySqlDialect;
use OrmUniversal\Relational\Dialect\OracleDialect;
use OrmUniversal\Relational\Dialect\PostgreSqlDialect;
use OrmUniversal\Relational\Dialect\SqliteDialect;
use OrmUniversal\Relational\Dialect\SqlServerDialect;
use OrmUniversal\Relational\Migration\SchemaOperation;
use PHPUnit\Framework\TestCase;

final class DdlGoldenTest extends TestCase
{
    private function table(): TableDefinition
    {
        return new TableDefinition(
            name: 'orders',
            columns: [
                new ColumnDefinition(name: 'id', databaseType: 'bigint', kind: TypeKind::BigInteger, nullable: false, autoIncrement: true),
                new ColumnDefinition(name: 'customer_id', databaseType: 'bigint', kind: TypeKind::BigInteger, nullable: false),
                new ColumnDefinition(name: 'total', databaseType: 'decimal(12,2)', kind: TypeKind::Decimal, nullable: false, default: 0),
                new ColumnDefinition(name: 'active', databaseType: 'boolean', kind: TypeKind::Boolean, nullable: false, default: true),
            ],
            indexes: [
                new IndexDefinition(name: 'orders_customer_idx', columns: ['customer_id']),
            ],
            foreignKeys: [
                new ForeignKeyDefinition(name: 'orders_customer_fk', columns: ['customer_id'], foreignTable: 'customers', foreignColumns: ['id'], onDelete: 'cascade'),
            ],
            options: ['primary' => ['id']],
        );
    }

    public function test_create_table_mysql(): void
    {
        $statements = MySqlDialect::make('8.4.3')->migrationCompiler()->compile(SchemaOperation::createTable($this->table()));

        self::assertSame(
            'create table `orders` (`id` bigint not null auto_increment, `customer_id` bigint not null, `total` decimal(12,2) not null default 0, `active` boolean not null default true, primary key (`id`), foreign key (`customer_id`) references `customers` (`id`) on delete CASCADE)',
            $statements[0]->sql,
        );
        self::assertSame(
            'create index `orders_customer_idx` on `orders` (`customer_id`)',
            $statements[1]->sql,
        );
    }

    public function test_create_table_postgres(): void
    {
        $statements = PostgreSqlDialect::make('18.0')->migrationCompiler()->compile(SchemaOperation::createTable($this->table()));

        self::assertStringContainsString('"id" bigint not null generated by default as identity', $statements[0]->sql);
        self::assertStringContainsString('foreign key ("customer_id") references "customers" ("id") on delete CASCADE', $statements[0]->sql);
    }

    public function test_create_table_sqlserver_and_oracle(): void
    {
        $sqlServer = SqlServerDialect::make('2022')->migrationCompiler()->compile(SchemaOperation::createTable($this->table()));
        self::assertStringContainsString('[id] bigint not null identity(1,1)', $sqlServer[0]->sql);

        $oracle = OracleDialect::make('19.0')->migrationCompiler()->compile(SchemaOperation::createTable($this->table()));
        self::assertStringContainsString('"id" bigint not null generated by default on null as identity', $oracle[0]->sql);
        self::assertStringContainsString('create index "orders_customer_idx" on "orders" ("customer_id")', $oracle[1]->sql);
    }

    public function test_sqlite_rejects_add_foreign_key_on_existing_table(): void
    {
        $compiler = SqliteDialect::make('3.49.2')->migrationCompiler();
        $operation = SchemaOperation::addForeignKey('orders', new ForeignKeyDefinition('fk', ['customer_id'], 'customers', ['id']));

        self::assertFalse($compiler->supports($operation));
    }

    public function test_mariadb_and_mysql_share_ddl_shape(): void
    {
        $mysql = MySqlDialect::make('8.4.3')->migrationCompiler()->compile(SchemaOperation::createTable($this->table()))[0]->sql;
        $mariadb = MariaDbDialect::make('11.6.2')->migrationCompiler()->compile(SchemaOperation::createTable($this->table()))[0]->sql;

        self::assertSame($mysql, $mariadb);
    }
}
